// One-off generator for the hidden map (/off-the-map): a dot grid of the land, each dot tagged with its country.
// Run from a folder where world-atlas, topojson-client and d3-geo are installed:
//   node scripts/places_dots.mjs > assets/places/dots.js
import { createRequire } from 'module';
const require = createRequire(import.meta.url);
const atlas = require('world-atlas/countries-50m.json');
const { feature } = require('topojson-client');
const { geoContains, geoBounds } = require('d3-geo');
const STEP = 2, LAT_TOP = 76, LAT_BOTTOM = -56;
const fc = feature(atlas, atlas.objects.countries).features.filter(f => f.properties.name !== 'Antarctica');
const boxes = fc.map(f => geoBounds(f));
const names = [], index = {}, dots = [];
for (let lat = LAT_TOP; lat >= LAT_BOTTOM; lat -= STEP) {
  for (let lon = -180 + STEP / 2; lon < 180; lon += STEP) {
    for (let i = 0; i < fc.length; i++) {
      const [[x0, y0], [x1, y1]] = boxes[i];
      const inLon = x0 <= x1 ? (lon >= x0 && lon <= x1) : (lon >= x0 || lon <= x1);
      if (!inLon || lat < y0 || lat > y1) continue;
      if (geoContains(fc[i], [lon, lat])) {
        const n = fc[i].properties.name;
        if (!(n in index)) { index[n] = names.length; names.push(n); }
        dots.push(Math.round((lon + 180) / STEP - 0.5), Math.round((LAT_TOP - lat) / STEP), index[n]);
        break;
      }
    }
  }
}
process.stdout.write('/* generated by scripts/places_dots.mjs: land dots every ' + STEP + '°, [col, row, country] triplets */\n' +
  'window.PLACES_GRID = ' + JSON.stringify({ step: STEP, top: LAT_TOP, names, dots }) + ';\n');
